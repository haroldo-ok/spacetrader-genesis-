out_h.append('extern const u8 gfx_tribble_pos[%d][2];   /* Palm form coordinates */' % len(trib))
out_h += ['extern const GfxPic gfx_pic[%d];' % len(PICS), 'enum { %s };' % ', '.join(n for _, n in PICS), '', '#endif']
