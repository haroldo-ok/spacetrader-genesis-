# ---- text: alerts and help strings ----------------------------------------
def cstr(b):
    s = b.decode('mac_roman').replace('\r', '\n')
    o = ''
    for ch in s:
        if ch == '\\': o += '\\\\'
        elif ch == '"': o += '\\"'
        elif ch == '\n': o += '\\n'
        elif ch in '‘’': o += "'"
        elif ch in '“”': o += '\\"'
        elif ch == '…': o += '...'
        elif 32 <= ord(ch) < 127: o += ch
        else: o += '?'
    return '"' + o + '"'
tc = ['/* GENERATED by tools/convert_assets.py from the original Palm resources. */', '#include "text_data.h"', '']
al = []
for aid, d in sorted(MAIN['Talt'].items()):
    atype, helpid, nb, defb = struct.unpack('>HHHH', d[:8])
    parts = d[8:].split(b'\0')
    title, msg, btns = parts[0], parts[1], parts[2:2 + nb]
    al.append('{%d,%d,%d,%d,%d,%s,%s,{%s}}' % (aid, atype, helpid, nb, defb, cstr(title), cstr(msg),
              ','.join(cstr(b) for b in btns)))
tc.append('const AlertDef text_alerts[] = {\n%s,\n{0,0,0,0,0,0,0,{0}}};' % ',\n'.join(al))
st = ['{%d,%s}' % (sid, cstr(d.rstrip(b'\0'))) for sid, d in sorted(MAIN['tSTR'].items())]
tc.append('const StringDef text_strings[] = {\n%s,\n{0,0}};' % ',\n'.join(st))
sl = []
for lid, d in sorted(MAIN['tSTL'].items()):
    z = d.index(b'\0')
    n = struct.unpack('>H', d[z + 1:z + 3])[0]
    items = d[z + 3:].split(b'\0')[:n]
    tc.append('static const char* const _sl%d[] = {%s};' % (lid, ','.join(cstr(i) for i in items)))
    sl.append('{%d,%d,_sl%d}' % (lid, n, lid))
tc.append('const StringListDef text_stringlists[] = {\n%s,\n{0,0,0}};' % ',\n'.join(sl))
open(os.path.join(ROOT, 'src/text_data.c'), 'w').write('\n'.join(tc) + '\n')
