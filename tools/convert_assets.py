#!/usr/bin/env python3
"""Convert the ORIGINAL Space Trader 1.2.2 Palm resources (assets_src/*.rsrc,
Mac resource forks from the GPL source release) into C tables for the
Genesis port:  src/gfx_data.c/.h  (bitmaps, palettes, pictures)
               src/text_data.c/.h (alerts, help strings)
Run:  python3 tools/convert_assets.py      (needs Pillow)
"""
import os, sys, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rsrcfork import read_fork
from pict import decode

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COL = read_fork(os.path.join(ROOT, 'assets_src/MerchantColor.rsrc'))['PICT']
MAIN = read_fork(os.path.join(ROOT, 'assets_src/Merchant.rsrc'))

def g3(c):            # 8-bit RGB -> Genesis 3-bit per channel
    return tuple(min(7, (v + 18) // 36) for v in c)
def gword(c):         # Genesis palette word 0000BBB0GGG0RRR0
    return (c[2] << 9) | (c[1] << 5) | (c[0] << 1)
def dist(a, b): return sum((x - y) ** 2 for x, y in zip(a, b))

def load(pid):
    im = decode(COL[pid]).convert('RGB')
    w, h = im.size
    px = [[g3(im.getpixel((x, y))) for x in range(w)] for y in range(h)]
    return w, h, px

WHITE = (7, 7, 7); BLACK = (0, 0, 0)

def knock_white_all(img):
    w, h, px = img
    return w, h, [[None if c == WHITE else c for c in row] for row in px]

def knock_white_border(img):
    w, h, px = img
    px = [row[:] for row in px]
    st = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while st:
        x, y = st.pop()
        if 0 <= x < w and 0 <= y < h and px[y][x] == WHITE:
            px[y][x] = None
            st += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return w, h, px

def build_pal(imgs, maxc=14):
    """shared palette for a group; black and None -> index 0."""
    cnt = {}
    for w, h, px in imgs:
        for row in px:
            for c in row:
                if c is not None and c != BLACK: cnt[c] = cnt.get(c, 0) + 1
    cols = sorted(cnt, key=lambda c: -cnt[c])
    remap = {}
    while len(cols) > maxc:      # merge the closest pair (drop rarer one)
        best = None
        for i in range(len(cols)):
            for j in range(i + 1, len(cols)):
                d = dist(cols[i], cols[j])
                if best is None or d < best[0] or (d == best[0] and cnt[cols[j]] < cnt[cols[best[2]]]): best = (d, i, j)
        _, i, j = best
        remap[cols[j]] = cols[i]; cols.pop(j)
    def idx(c):
        if c is None or c == BLACK: return 0
        while c in remap: c = remap[c]
        return cols.index(c) + 1
    return cols, idx

out_c = ['/* GENERATED by tools/convert_assets.py from the original Palm resources. */',
         '#include "gfx_data.h"', '']
out_h = ['/* GENERATED by tools/convert_assets.py - do not edit. */', '#ifndef GFX_DATA_H', '#define GFX_DATA_H',
         '#include "genesis.h"', '',
         'typedef struct { u8 w, h; const u8* pix; } GfxBmp;   /* 1 byte/pixel, 0 = transparent */',
         'typedef struct { u16 ntiles; const u32* tiles; const u16* map; const u16* pal; } GfxPic; /* 20x20 tiles, pal = 4x14 */', '']
uid = [0]
def emit_bmp(img, idx):
    w, h, px = img
    uid[0] += 1
    name = '_b%d' % uid[0]
    data = [idx(c) for row in px for c in row]
    out_c.append('static const u8 %s[] = {%s};' % (name, ','.join(map(str, data))))
    return '{%d,%d,%s}' % (w, h, name)
def emit_pal(name, cols, n=14):
    v = [gword(c) for c in cols] + [0] * (n - len(cols))
    out_c.append('const u16 %s[%d] = {%s};' % (name, n, ','.join('0x%04X' % x for x in v)))
    out_h.append('extern const u16 %s[%d];' % (name, n))

# ---- ships: normal, damaged, shielded, shielded+damaged -------------------
SH = [(5300, 5500, 0, 0), (6100, 6300, 0, 0)]
SH += [tuple(6900 + i * 800 + k * 200 for k in range(4)) for i in range(8)]
SH += [(13300, 13500, 0, 0), (14100, 14300, 14500, 14700), (14900, 15100, 15300, 15500),
       (15700, 16100, 0, 0), (15900, 15900, 0, 0)]
rows = []; pals = []
for ids in SH:
    ids = [ids[0], ids[1], ids[2] or ids[0], ids[3] or ids[1]]
    imgs = [knock_white_all(load(i)) for i in ids]
    cols, idx = build_pal(imgs)
    rows.append('{' + ','.join(emit_bmp(im, idx) for im in imgs) + '}')
    pals.append(cols)
out_c.append('const GfxBmp gfx_ship[%d][4] = {\n%s};' % (len(SH), ',\n'.join(rows)))
out_c.append('const u16 gfx_ship_pal[%d][14] = {%s};' % (len(SH), ','.join(
    '{' + ','.join('0x%04X' % gword(c) for c in cols + [BLACK] * (14 - len(cols))) + '}' for cols in pals)))
out_h += ['#define GFX_NSHIPS %d' % len(SH), 'extern const GfxBmp gfx_ship[GFX_NSHIPS][4];',
          'extern const u16 gfx_ship_pal[GFX_NSHIPS][14];']

def group(name, ids, enum, knock=knock_white_border):
    imgs = [knock(load(i)) for i in ids]
    cols, idx = build_pal(imgs)
    out_c.append('const GfxBmp %s[%d] = {%s};' % (name, len(ids), ','.join(emit_bmp(im, idx) for im in imgs)))
    out_h.append('extern const GfxBmp %s[%d];' % (name, len(ids)))
    out_h.append('enum { %s };' % ', '.join(enum))
    emit_pal(name + '_pal', cols)

group('gfx_chart', [3300, 3500, 3700, 3900, 4100, 4300, 4500, 4700],
      ['CH_SYSTEM', 'CH_CURRENT', 'CH_SHORTRANGE', 'CH_VISITED', 'CH_CURRENTVISITED',
       'CH_VISITEDSHORTRANGE', 'CH_WORMHOLE', 'CH_SMALLWORMHOLE'])
group('gfx_icon', [16900, 17100, 17300, 17500, 18100, 17700, 17900],
      ['IC_PIRATE', 'IC_POLICE', 'IC_TRADER', 'IC_ALIEN', 'IC_SPECIAL', 'IC_ATTACK', 'IC_ATTACK2'])
group('gfx_about', [18200], ['AB_ICON'])

# ---- 160x160 pictures: 4 palettes x 14 colours, palette chosen per tile ----
def picture(pid):
    w, h, px = load(pid)
    tiles = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            tiles.append([px[ty * 8 + y][tx * 8 + x] for y in range(8) for x in range(8)])
    tsets = [set(c for c in t if c != BLACK) for t in tiles]
    pals = [[] for _ in range(4)]
    assign = [None] * len(tiles)
    order = sorted(range(len(tiles)), key=lambda i: -len(tsets[i]))
    def err(i, p):
        e = 0
        for c in tiles[i]:
            if c != BLACK: e += min([dist(c, q) for q in pals[p]] + [dist(c, BLACK)])
        return e
    for i in order:
        best = None
        for p in range(4):
            new = [c for c in tsets[i] if c not in pals[p]]
            if len(pals[p]) + len(new) <= 14:
                k = (len(new), len(pals[p]))
                if best is None or k < best[0]: best = (k, p, new)
        if best:
            pals[best[1]] += best[2]; assign[i] = best[1]
    for i in order:
        if assign[i] is None: assign[i] = min(range(4), key=lambda p: err(i, p))
    words = []; uniq = {}; mp = []
    for i, t in enumerate(tiles):
        p = assign[i]
        def ix(c):
            if c == BLACK: return 0
            if c in pals[p]: return pals[p].index(c) + 1
            cand = [(dist(c, BLACK), 0)] + [(dist(c, q), k + 1) for k, q in enumerate(pals[p])]
            return min(cand)[1]
        tw = []
        for y in range(8):
            v = 0
            for x in range(8): v = (v << 4) | ix(t[y * 8 + x])
            tw.append(v)
        key = tuple(tw)
        if key not in uniq: uniq[key] = len(uniq); words += tw
        mp.append((p << 13) | uniq[key])
    return len(uniq), words, mp, pals
PICS = [(4900, 'PIC_TITLE'), (16500, 'PIC_RETIRE'), (5100, 'PIC_UTOPIA'), (16700, 'PIC_DESTROYED')]
ent = []
for n, (pid, nm) in enumerate(PICS):
    nt, words, mp, pals = picture(pid)
    out_c.append('static const u32 _pt%d[] = {%s};' % (n, ','.join('0x%08X' % v for v in words)))
    out_c.append('static const u16 _pm%d[] = {%s};' % (n, ','.join('0x%04X' % v for v in mp)))
    flat = []
    for p in pals: flat += [gword(c) for c in p] + [0] * (14 - len(p))
    out_c.append('static const u16 _pp%d[] = {%s};' % (n, ','.join('0x%04X' % v for v in flat)))
    ent.append('{%d,_pt%d,_pm%d,_pp%d}' % (nt, n, n, n))
out_c.append('const GfxPic gfx_pic[%d] = {%s};' % (len(PICS), ','.join(ent)))
import re
hdr = open(os.path.join(ROOT, 'src/MerchantRsc.h'), 'rb').read().decode('latin1')
trib = re.findall(r'#define EncounterTribble(\d+)Button\s+\d+\s+//\(Left Origin = (\d+), Top Origin = (\d+)', hdr)
